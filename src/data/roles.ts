/**
 * Canonical roles that power the whole salary engine.
 * Medians are 2026 US national base-salary estimates (USD) per level; verified guide roles
 * (Software Engineer, DevOps Engineer, etc.) reuse the figures from docs/payscope-feature-catalog.md §8.
 * `coreSkills[].skill` values reference names in src/data/skills.ts; `certifications` reference names in src/data/certs.ts.
 */
import type { RoleDef } from "./types";

type L4 = [entry: number, mid: number, senior: number, lead: number];
type Lad = [title: string, years: string, description: string, dayToDay: string];

function slugify(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
}

function role(
  name: string,
  category: RoleDef["category"],
  aliases: string[],
  medians: L4,
  p: [p25: number, p75: number],
  coreSkills: [string, number][],
  certifications: string[],
  supplyDemandRatio: number,
  activeRolesUS: number,
  whatTheyDo: string,
  ladder: [Lad, Lad, Lad, Lad],
  specializations: [string, string][],
  topEmployers: [string, number][],
): RoleDef {
  const [entry, mid, senior, lead] = medians;
  const mk = (t: Lad) => ({ title: t[0], years: t[1], description: t[2], dayToDay: t[3] });
  return {
    name,
    slug: slugify(name),
    category,
    aliases,
    medians: { entry, mid, senior, lead },
    p25: p[0],
    p75: p[1],
    coreSkills: coreSkills.map(([skill, weight]) => ({ skill, weight })),
    certifications,
    supplyDemandRatio,
    activeRolesUS,
    ladder: { entry: mk(ladder[0]), mid: mk(ladder[1]), senior: mk(ladder[2]), lead: mk(ladder[3]) },
    whatTheyDo,
    specializations: specializations.map(([n, d]) => ({ name: n, description: d })),
    topEmployers: topEmployers.map(([company, openings]) => ({ company, openings })),
  };
}

